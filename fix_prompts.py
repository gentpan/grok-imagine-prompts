def fix_file(filepath: Path) -> bool:
    """修复单个文件，返回是否有修改"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    original_content = content
    modified = False
    
    # 1. 检查是否有预定义的完整替换
    if str(filepath) in FIXES:
        fix_data = FIXES[str(filepath)]
        # 更新标题
        content = re.sub(r'title_zh: .*', f"title_zh: {fix_data['title_zh']}", content)
        content = re.sub(r'title_en: .*', f"title_en: {fix_data['title_en']}", content)
        # 更新中文内容
        content = re.sub(
            r'(## 中文\n\n\*\*[^*]*\*\*\n\n).*?(?=\n## English)',
            r'\1' + fix_data['chinese'] + '\n',
            content,
            flags=re.DOTALL
        )
        # 更新英文内容
        content = re.sub(
            r'(## English\n\n\*\*[^*]*\*\*\n\n).*?(?=\n---)',
            r'\1' + fix_data['english'] + '\n',
            content,
            flags=re.DOTALL
        )
        modified = True
    else:
        # 2. 提取分类
        category_match = re.search(r'category: (\S+)', content)
        category = category_match.group(1) if category_match else ''
        
        # 3. 处理中文部分有英文的情况
        chinese_match = re.search(r'(## 中文\n\n\*\*[^*]*\*\*\n\n)(.*?)(?=\n## English)', content, re.DOTALL)
        if chinese_match:
            chinese_section = chinese_match.group(2).strip()
            # 移除 [技术性 prompt，建议使用英文原文] 标记
            if '[技术性 prompt' in chinese_section:
                # 找到对应的英文内容
                english_match = re.search(r'## English\n\n\*\*[^*]*\*\*\n\n(.*?)(?=\n---)', content, re.DOTALL)
                if english_match:
                    english_text = english_match.group(1).strip()
                    # 翻译英文到中文
                    translated_chinese = translate_to_chinese(english_text)
                    content = re.sub(
                        r'(## 中文\n\n\*\*[^*]*\*\*\n\n).*?(?=\n## English)',
                        r'\1' + translated_chinese + '\n',
                        content,
                        flags=re.DOTALL
                    )
                    modified = True
        
        # 4. 处理过短的prompt
        english_match = re.search(r'(## English\n\n\*\*[^*]*\*\*\n\n)(.*?)(?=\n---)', content, re.DOTALL)
        if english_match:
            english_section = english_match.group(2).strip()
            # 去掉可能的整理行
            english_lines = [l for l in english_section.split('\n') if not l.startswith('整理：')]
            english_text = ' '.join(english_lines).strip()
            
            if len(english_text) < 80:
                enriched_zh, enriched_en = enrich_short_prompt(english_text, category)
                # 更新英文
                content = re.sub(
                    r'(## English\n\n\*\*[^*]*\*\*\n\n).*?(?=\n---)',
                    r'\1' + enriched_en + '\n',
                    content,
                    flags=re.DOTALL
                )
                # 更新中文
                content = re.sub(
                    r'(## 中文\n\n\*\*[^*]*\*\*\n\n).*?(?=\n## English)',
                    r'\1' + enriched_zh + '\n',
                    content,
                    flags=re.DOTALL
                )
                modified = True
    
    # 5. 清理页脚
    cleaned = clean_footer(content)
    if cleaned != content:
        content = cleaned
        modified = True
    
    # 6. 写回文件
    if modified and content != original_content:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        return True
    
    return False

