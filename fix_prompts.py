def clean_footer(content: str) -> str:
    """移除页脚的整理行"""
    content = re.sub(r'\n整理：\[gentpan\]\(https://github\.com/gentpan\)\s*\n', '\n', content)
    content = re.sub(r'\n整理：\[Yep\].*?\n', '\n', content)
    content = re.sub(r'\n整理：Yep.*?\n', '\n', content)
    return content

